// Package main реализует multichecker staticlint для проекта сервиса метрик.
//
// staticlint - это локальная команда проекта, которая объединяет в одном
// исполняемом файле несколько групп анализаторов:
//
//   - стандартные анализаторы из golang.org/x/tools/go/analysis/passes;
//   - все анализаторы класса SA из Staticcheck;
//   - один анализатор Staticcheck вне класса SA;
//   - несколько публичных сторонних анализаторов;
//   - собственный анализатор noosexit для правил проекта.
//
// # Запуск multichecker
//
// Сборка команды из корня репозитория:
//
//	go build -o staticlint ./cmd/staticlint
//
// Запуск проверки всего модуля:
//
//	./staticlint ./...
//
// Одноразовый запуск без отдельной сборки:
//
//	go run ./cmd/staticlint ./...
//
// Команда принимает те же шаблоны пакетов, что и multichecker, и выводит
// диагностику в стандартном формате go/analysis.
//
// Подключённые стандартные анализаторы
//
//   - appends: проверяет некорректные вызовы append.
//   - asmdecl: сверяет объявления Go с символами, используемыми в asm-файлах.
//   - assign: находит бесполезные присваивания вида x = x.
//   - atomic: проверяет типичные ошибки при использовании sync/atomic.
//   - bools: ищет подозрительные булевы выражения.
//   - buildtag: проверяет корректность ограничений //go:build и // +build.
//   - cgocall: сообщает о неверной передаче указателей в cgo.
//   - composite: предупреждает о неименованных полях в составных литералах внешних структур.
//   - copylock: находит нежелательное копирование значений, содержащих lock.
//   - defers: выявляет ошибки использования defer в циклах и ветвлениях.
//   - errorsas: проверяет аргументы, передаваемые в errors.As.
//   - httpresponse: ищет ошибки работы с HTTP-ответом до закрытия body.
//   - ifaceassert: сообщает о невозможных interface-to-interface type assertion.
//   - loopclosure: находит захват переменной цикла в замыканиях.
//   - lostcancel: проверяет, что cancel-функции контекста действительно используются.
//   - nilfunc: выявляет некорректные сравнения функций с nil.
//   - printf: проверяет форматные строки и аргументы Printf-подобных функций.
//   - shift: проверяет некорректные битовые сдвиги.
//   - sigchanyzer: проверяет каналы, передаваемые в os/signal.
//   - stdmethods: проверяет сигнатуры методов стандартных интерфейсов.
//   - stringintconv: ищет подозрительные преобразования string(int).
//   - structtag: проверяет корректность struct tag.
//   - tests: проверяет объявления тестов, бенчмарков, fuzz-тестов и examples.
//   - timeformat: проверяет layout-строки для времени.
//   - unmarshal: проверяет корректность аргументов для unmarshal/decode.
//   - unreachable: находит недостижимый код.
//   - unsafeptr: проверяет преобразования unsafe.Pointer.
//   - unusedresult: ищет проигнорированные результаты функций, которые нельзя безопасно отбрасывать.
//
// Подключённые анализаторы Staticcheck класса SA
//
//   - SA1000: некорректное регулярное выражение.
//   - SA1001: некорректный шаблон.
//   - SA1002: некорректный формат в time.Parse.
//   - SA1003: неподдерживаемый аргумент для функций из encoding/binary.
//   - SA1004: подозрительно маленькая нетипизированная константа в time.Sleep.
//   - SA1005: некорректный первый аргумент для exec.Command.
//   - SA1006: вызов Printf с динамическим первым аргументом и без остальных аргументов.
//   - SA1007: некорректный URL в net/url.Parse.
//   - SA1008: неканоничный ключ в карте http.Header.
//   - SA1010: вызов (*regexp.Regexp).FindAll с n == 0, который всегда возвращает пустой результат.
//   - SA1011: передача невалидного UTF-8 в функции пакета strings.
//   - SA1012: передача nil context.Context вместо context.TODO или context.Background.
//   - SA1013: аргументы io.Seeker.Seek переданы в неправильном порядке.
//   - SA1014: в Unmarshal или Decode передано неуказательное значение.
//   - SA1015: использование time.Tick в потенциально протекающем сценарии.
//   - SA1016: перехват сигнала, который нельзя перехватывать.
//   - SA1017: в os/signal.Notify передан небуферизованный канал.
//   - SA1018: вызов strings.Replace с n == 0.
//   - SA1019: использование устаревшего API.
//   - SA1020: некорректная пара host:port для net.Listen-подобной функции.
//   - SA1021: использование bytes.Equal для сравнения net.IP.
//   - SA1023: реализация io.Writer изменяет буфер, принадлежащий вызывающему коду.
//   - SA1024: в cutset строки есть дублирующиеся символы.
//   - SA1025: некорректное использование возвращаемого значения time.Timer.Reset.
//   - SA1026: попытка маршалинга канала или функции.
//   - SA1027: невыравненный 64-битный atomic-доступ.
//   - SA1028: sort.Slice вызван не для slice.
//   - SA1029: неподходящий ключ в context.WithValue.
//   - SA1030: некорректный аргумент в вызове strconv.
//   - SA1031: пересекающиеся byte slice переданы в кодировщик.
//   - SA1032: неправильный порядок аргументов в errors.Is.
//   - SA2000: sync.WaitGroup.Add вызывается внутри goroutine.
//   - SA2001: пустая критическая секция.
//   - SA2002: testing.T.FailNow или SkipNow вызваны из другой goroutine.
//   - SA2003: после Lock отложен Lock вместо Unlock.
//   - SA3000: TestMain не вызывает os.Exit.
//   - SA3001: бенчмарк присваивает значение в b.N.
//   - SA4000: одинаковые выражения по обе стороны бинарного оператора.
//   - SA4001: выражение &*x ошибочно воспринимается как копирование.
//   - SA4003: беззнаковое значение сравнивается с отрицательным.
//   - SA4004: цикл безусловно завершается после первой итерации.
//   - SA4005: присваивание полю, результат которого никогда не будет наблюдаем.
//   - SA4006: присвоенное значение перезаписывается до чтения.
//   - SA4008: переменная в условии цикла никогда не меняется.
//   - SA4009: аргумент функции перезаписывается до первого использования.
//   - SA4010: результат append нигде не используется.
//   - SA4011: оператор break не оказывает эффекта.
//   - SA4012: сравнение с NaN.
//   - SA4013: двойное отрицание булевого значения.
//   - SA4014: повторяющееся условие в цепочке if/else if.
//   - SA4015: бессмысленный вызов math.Ceil или похожей функции для значения, уже полученного из integer.
//   - SA4016: побитовая операция не даёт полезного эффекта.
//   - SA4017: отбрасывание результатов функции без побочных эффектов.
//   - SA4018: самоприсваивание.
//   - SA4019: дублирующиеся build constraint в одном файле.
//   - SA4020: недостижимый case в type switch.
//   - SA4021: выражение x = append(y) эквивалентно x = y.
//   - SA4022: адрес переменной сравнивается с nil.
//   - SA4023: невозможное сравнение interface со значением untyped nil.
//   - SA4024: невозможная проверка возвращаемого значения встроенной функции.
//   - SA4025: деление целочисленных литералов, которое всегда даёт ноль.
//   - SA4026: ошибочное предположение о существовании отрицательного нуля в константах Go.
//   - SA4027: результат URL.Query изменяется без обратной записи в URL.
//   - SA4028: выражение x % 1 всегда равно нулю.
//   - SA4029: неэффективная попытка отсортировать slice.
//   - SA4030: неэффективная попытка сгенерировать случайное число.
//   - SA4031: заведомо не-nil значение проверяется на nil.
//   - SA4032: runtime.GOOS или runtime.GOARCH сравниваются с невозможным значением.
//   - SA5000: присваивание в nil map.
//   - SA5001: Close откладывается до проверки ошибки.
//   - SA5002: пустой бесконечный цикл активно расходует CPU.
//   - SA5003: defer внутри бесконечного цикла никогда не выполнится.
//   - SA5004: for-select с пустой веткой default активно крутится.
//   - SA5005: finalizer удерживает финализируемый объект достижимым.
//   - SA5007: бесконечная рекурсия.
//   - SA5008: некорректный struct tag.
//   - SA5009: некорректный вызов Printf.
//   - SA5010: невозможный type assertion.
//   - SA5011: возможное разыменование nil pointer.
//   - SA5012: slice нечётной длины передан в функцию, ожидающую чётный размер.
//   - SA6000: regexp.Match-подобный вызов используется в цикле вместо предварительно скомпилированного regexp.
//   - SA6001: пропущена оптимизация при индексировании map по byte slice.
//   - SA6002: неуказательное значение сохраняется в sync.Pool.
//   - SA6003: строка преобразуется в []rune перед range без необходимости.
//   - SA6005: неэффективное сравнение строк через strings.ToLower или strings.ToUpper.
//   - SA6006: io.WriteString используется для записи []byte.
//   - SA9001: defer внутри range-цикла может выполниться позже, чем ожидается.
//   - SA9002: литерал FileMode выглядит как восьмеричный, но им не является.
//   - SA9003: пустое тело в ветке if или else.
//   - SA9004: только первая константа в группе имеет явный тип.
//   - SA9005: маршалинг структуры без экспортируемых полей.
//   - SA9006: сомнительный битовый сдвиг фиксированного целочисленного типа.
//   - SA9007: подозрительное удаление директории.
//   - SA9008: ветка else type assertion читает не то значение.
//   - SA9009: неэффективная директива компилятора Go.
//
// Подключённый анализатор Staticcheck другого класса
//
//   - S1039: сообщает о лишнем использовании fmt.Sprint с единственным строковым аргументом.
//
// Подключённые публичные анализаторы
//
//   - gocheckcompilerdirectives: проверяет корректность директив компилятора Go, включая //go:build и другие //go:-комментарии.
//   - ineffassign: находит неэффективные присваивания.
//   - nilerr: сообщает о возврате nil при ненулевой ошибке и о возврате ошибки при заведомо nil err.
//
// Собственный анализатор
//
//   - noosexit: запрещает прямой вызов os.Exit внутри верхнеуровневой функции main пакета main.
//     Анализатор игнорирует сгенерированные файлы, создаваемые go test, чтобы синтетический
//     _testmain не давал ложных срабатываний. Смысл правила - вынести завершение процесса из main
//     в тестируемую прикладную логику и не прятать управление завершением программы.
